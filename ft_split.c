#include "libft.h"

/**
 * "hola que tal como estas"
 * " "
 * 
 * "hola" "que" "tal" "como" "estas"
 * 
 * "4234012300001207605675670"
 * "0"
 * 
 * "4234" "123" "12" "76" "56767"
 */


char	**ft_split(char const *s, char c)
{
	int	i;

	if (!s)
		return (NULL);

	i = 0;
	while(s[i])
	{
		if (s[i] == c)
		{
			i++;
			continue;
		}

	}
	
	
}